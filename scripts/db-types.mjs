// Regenerates lib/db/database.types.ts from the live schema with the Supabase CLI (no Docker needed).
//   npm run db:types

import { execFileSync } from "node:child_process"
import { writeFile } from "node:fs/promises"
import path from "node:path"

const ROOT = path.resolve(import.meta.dirname, "..")
const OUT = path.join(ROOT, "lib", "db", "database.types.ts")

if (!process.env.SUPABASE_DB_URL) throw new Error("SUPABASE_DB_URL is not set (see .env.example)")

// Invoke the CLI through node directly (no shell), so the URL is never shell-interpreted.
const types = execFileSync(
  process.execPath,
  [
    path.join(ROOT, "node_modules", "supabase", "dist", "supabase.js"),
    "gen",
    "types",
    "typescript",
    "--db-url",
    process.env.SUPABASE_DB_URL,
    "--schema",
    "public",
  ],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], maxBuffer: 16 * 1024 * 1024 }
)

await writeFile(OUT, `// Generated by \`npm run db:types\`. Do not edit by hand.\n\n${types}`)
execFileSync(process.execPath, [path.join(ROOT, "node_modules", "prettier", "bin", "prettier.cjs"), "--write", OUT], {
  stdio: "inherit",
})
console.log(`Wrote ${path.relative(ROOT, OUT)}`)
