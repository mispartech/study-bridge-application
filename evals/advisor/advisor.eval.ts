import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { expect, it } from "vitest"

import { gradeRun, type EvalCase, type EvalRun } from "@/lib/advisor/grade"
import { advisorTurn } from "@/lib/advisor/run"
import type { AdvisorContext } from "@/lib/advisor/tools"
import { modelFor } from "@/lib/ai"
import { matchProfile, type Catalogue, type MatchProfile } from "@/lib/match"
import demo from "@/tests/fixtures/demo-catalogue.json"

import { buildCases } from "./cases"
import retestIds from "./retest.json"

const NOW = new Date("2026-11-05T12:00:00Z")
const PASS_MARK = 0.95
const CONCURRENCY = Number(process.env.EVAL_CONCURRENCY ?? 3)
const MAX_ATTEMPTS = 6
const BASE_BACKOFF_MS = 15_000
const KOBO = 100
// `npm run eval:advisor:retest`: last run's failures plus the trick questions, reported separately.
const retest = import.meta.env.MODE === "retest"
const suffix = retest ? "-retest" : process.env.EVAL_ONLY ? `-${process.env.EVAL_ONLY}` : ""
const resultsPath = fileURLToPath(new URL(`./results${suffix}.jsonl`, import.meta.url))
const reportPath = fileURLToPath(new URL(`./report${suffix}.md`, import.meta.url))
const TRICKS = ["invented_fee", "visa_law", "agent_link"]

const student = (nationality: string): MatchProfile =>
  matchProfile.parse({
    nationality,
    degree_class: "upper_second",
    cgpa: 3.8,
    cgpa_scale: 5,
    field: "computer_data_science",
    ielts: 7,
    budget_total_minor: 80_000_000 * KOBO,
    target_cycle: "2027/28",
    target_term: "fall",
    accommodation_pref: "university_halls",
  })

function contextFor(testCase: EvalCase): AdvisorContext {
  return {
    profile: student(testCase.persona === "nigerian" ? "NG" : "GH"),
    catalogue: demo as unknown as Catalogue,
    options: { now: NOW, demoMode: true },
    addToShortlist: async () => "added",
  }
}

async function attempt(testCase: EvalCase): Promise<EvalRun> {
  const run: EvalRun = { answer: "", tools: [] }
  for await (const event of advisorTurn([{ role: "user", content: testCase.question }], contextFor(testCase), [])) {
    if (event.type === "text") {
      run.answer += event.text
      run.fallback = event.fallback
    } else if (event.type === "tool") run.tools.push({ name: event.name, output: event.output })
    else if (event.type === "error") run.error = event.message
  }
  return run
}

const retryable = (message: string) =>
  /429|quota|rate|resource.?exhausted|503|overloaded|unavailable|timeout/i.test(message)

async function runCase(testCase: EvalCase): Promise<EvalRun> {
  for (let tries = 1; ; tries++) {
    let run: EvalRun
    try {
      run = await attempt(testCase)
    } catch (err) {
      run = { answer: "", tools: [], error: err instanceof Error ? err.message : String(err) }
    }
    if (!run.error || !retryable(run.error) || tries === MAX_ATTEMPTS) return run
    await new Promise((resolve) => setTimeout(resolve, BASE_BACKOFF_MS * 2 ** (tries - 1)))
  }
}

type Line = {
  id: string
  category: string
  question: string
  passed: boolean
  failures: string[]
  answer: string
  tools: string[]
}

function report(lines: Line[], total: number) {
  const categories = [...new Set(lines.map((l) => l.category))]
  const rows = categories.map((category) => {
    const inCategory = lines.filter((l) => l.category === category)
    const passed = inCategory.filter((l) => l.passed).length
    return `| ${category} | ${inCategory.length} | ${passed} | ${((100 * passed) / inCategory.length).toFixed(1)}% |`
  })
  const passed = lines.filter((l) => l.passed).length
  const failed = lines.filter((l) => !l.passed).map((l) => `- **${l.id}** "${l.question}": ${l.failures.join("; ")}`)
  const { provider, model } = modelFor("advisor")
  return [
    "# Advisor eval",
    "",
    `Model: ${provider} ${model}. Answered ${lines.length} of ${total}. Generated by \`npm run eval:advisor\`.`,
    "",
    `**Overall: ${passed}/${lines.length} (${((100 * passed) / Math.max(1, lines.length)).toFixed(1)}%)**, pass mark ${PASS_MARK * 100}%.`,
    "",
    "| Category | Questions | Passed | Pass rate |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
    "## Failures",
    "",
    ...(failed.length ? failed : ["None."]),
    "",
  ].join("\n")
}

it("passes the advisor eval", async () => {
  const cases = buildCases()
    .filter((c) => !process.env.EVAL_ONLY || c.category === process.env.EVAL_ONLY)
    .filter((c) => !retest || TRICKS.includes(c.category) || retestIds.includes(c.id))
  const resume = process.env.EVAL_RESUME === "1" && existsSync(resultsPath)
  const previous: Line[] = resume
    ? readFileSync(resultsPath, "utf8")
        .split("\n")
        .filter(Boolean)
        .map((l) => JSON.parse(l) as Line)
    : []
  if (!resume) writeFileSync(resultsPath, "")
  // Provider errors are retried on resume; only answered questions count as done.
  const lines = previous.filter((l) => !l.failures.some((f) => f.startsWith("error:")))
  const done = new Set(lines.map((l) => l.id))
  const queue = cases.filter((c) => !done.has(c.id))

  await Promise.all(
    Array.from({ length: CONCURRENCY }, async () => {
      for (let next = queue.shift(); next; next = queue.shift()) {
        const run = await runCase(next)
        const { passed, failures } = gradeRun(next, run)
        const line = {
          id: next.id,
          category: next.category,
          question: next.question,
          passed,
          failures,
          answer: run.answer,
          tools: run.tools.map((t) => t.name),
        }
        lines.push(line)
        appendFileSync(resultsPath, `${JSON.stringify(line)}\n`)
        writeFileSync(reportPath, report(lines, cases.length))
      }
    })
  )
  const rate = lines.filter((l) => l.passed).length / cases.length
  expect(rate).toBeGreaterThanOrEqual(PASS_MARK)
})
